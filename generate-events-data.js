const fs = require('fs');
const path = require('path');

// Function to generate events data from image files
function generateEventsData() {
    const eventsDir = path.join(__dirname, 'static/images/events');
    
    try {
        const files = fs.readdirSync(eventsDir);
        const imageFiles = files.filter(file => 
            /\.(jpg|jpeg|png|svg)$/i.test(file)
        );
        
        const eventsData = imageFiles.map((filename, index) => {
            const nameWithoutExt = filename.replace(/\.(jpg|jpeg|png|svg)$/i, '');
            const eventName = nameWithoutExt
                .split('-')
                .map(word => word.charAt(0).toUpperCase() + word.slice(1))
                .join(' ');
            
            // Generate a date (weekly events starting from current date)
            const baseDate = new Date();
            baseDate.setDate(baseDate.getDate() + (index * 7));
            
            return {
                filename: filename,
                name: eventName,
                date: baseDate.toLocaleDateString('en-US', { 
                    year: 'numeric', 
                    month: 'long', 
                    day: 'numeric' 
                })
            };
        });
        
        const jsContent = `// Auto-generated events data based on images in the events folder
// This file can be regenerated by running the build script

window.eventsImageData = ${JSON.stringify(eventsData, null, 4)};
`;
        
        fs.writeFileSync(path.join(__dirname, 'static/js/events-data.js'), jsContent);
        console.log(`Generated events data for ${eventsData.length} images`);
        
    } catch (error) {
        console.error('Error generating events data:', error);
    }
}

// Run if called directly
if (require.main === module) {
    generateEventsData();
}

module.exports = generateEventsData;