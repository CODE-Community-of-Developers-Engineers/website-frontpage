#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

// Configuration
const EVENTS_DIR = path.join(__dirname, '..', 'static', 'images', 'events');
const OUTPUT_FILE = path.join(__dirname, '..', 'static', 'js', 'events-data.js');

// Function to convert filename to readable name
function filenameToName(filename) {
    let name = filename
        .replace(/\.(svg|jpg|jpeg|png|webp)$/i, '') // Remove extension
        .replace(/[-_]/g, ' '); // Replace hyphens and underscores with spaces
    
    // Handle camelCase and add spaces before capital letters (but not at the start)
    name = name.replace(/([a-z])([A-Z])/g, '$1 $2');
    
    // Add spaces before numbers that follow letters
    name = name.replace(/([a-zA-Z])(\d)/g, '$1 $2');
    
    // Add spaces after numbers that are followed by letters
    name = name.replace(/(\d)([a-zA-Z])/g, '$1 $2');
    
    // Handle common compound words by adding spaces
    name = name.replace(/weekend/gi, 'Weekend ');
    name = name.replace(/coding/gi, 'Coding ');
    name = name.replace(/sessions/gi, 'Sessions');
    name = name.replace(/workshops/gi, 'Workshops');
    name = name.replace(/hackathon/gi, 'Hackathon');
    
    // Clean up extra spaces and capitalize
    name = name.replace(/\s+/g, ' ') // Replace multiple spaces with single space
        .trim() // Remove leading/trailing spaces
        .replace(/\b\w/g, char => char.toUpperCase()); // Capitalize first letter of each word
    
    return name;
}

// Function to generate a future date for events
function generateEventDate(index) {
    const today = new Date();
    const futureDate = new Date(today);
    futureDate.setMonth(today.getMonth() + index); // Monthly intervals
    
    return futureDate.toLocaleDateString('en-US', {
        year: 'numeric',
        month: 'long'
    });
}

// Main function to generate events data
function generateEventsData() {
    try {
        // Check if events directory exists
        if (!fs.existsSync(EVENTS_DIR)) {
            console.log('Events directory not found, creating with default images...');
            fs.mkdirSync(EVENTS_DIR, { recursive: true });
            
            // Create a default SVG if no images exist
            const defaultSvg = `<svg viewBox="0 0 400 300" xmlns="http://www.w3.org/2000/svg">
                <rect width="400" height="300" fill="#E9E3DC"/>
                <text x="200" y="150" text-anchor="middle" font-family="Arial" font-size="24" fill="#59969B">Code & Coffee Event</text>
            </svg>`;
            
            fs.writeFileSync(path.join(EVENTS_DIR, 'default-event.svg'), defaultSvg);
        }

        // Read all image files from the events directory
        const files = fs.readdirSync(EVENTS_DIR);
        const imageFiles = files.filter(file => 
            /\.(svg|jpg|jpeg|png|webp)$/i.test(file)
        ).sort(); // Sort alphabetically for consistent ordering

        if (imageFiles.length === 0) {
            console.warn('No image files found in events directory');
            return;
        }

        // Generate events data
        const eventsData = imageFiles.map((filename, index) => ({
            filename: filename,
            name: filenameToName(filename),
            date: generateEventDate(index)
        }));

        // Generate the JavaScript file content
        const jsContent = `// Auto-generated events data based on images in the events folder
// This file can be regenerated by running the build script

window.eventsImageData = ${JSON.stringify(eventsData, null, 4)};
`;

        // Write the events data file
        fs.writeFileSync(OUTPUT_FILE, jsContent);
        
        console.log(`✓ Generated events data for ${eventsData.length} images`);
        console.log('Events:', eventsData.map(e => e.name).join(', '));
        console.log('Output file path:', OUTPUT_FILE);
        console.log('File size:', fs.statSync(OUTPUT_FILE).size, 'bytes');
        
    } catch (error) {
        console.error('Error generating events data:', error);
        process.exit(1);
    }
}

// Run the script
if (require.main === module) {
    generateEventsData();
}

module.exports = { generateEventsData };